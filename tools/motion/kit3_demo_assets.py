def gradient(w, h, top, bottom):
    t = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    a = np.array(top, np.float32)[None, None] * (1 - t) + np.array(bottom, np.float32)[None, None] * t
    return np.repeat(a, w, axis=1)


def grain(a, seed, amount=6.0):
    rng = np.random.default_rng(seed)
    n = rng.normal(0, amount, a.shape[:2]).astype(np.float32)[..., None]
    return np.clip(a + n, 0, 255).astype(np.uint8)


def poster(w, h, top, bottom, accent, seed, title="DEMO"):
    """a cover: a gradient, a big disc, a title band; no black border (a still can't tell a black edge from the stage)"""
    im = Image.fromarray(grain(gradient(w, h, top, bottom), seed))
    d = ImageDraw.Draw(im)
    r = int(0.34 * w)
    d.ellipse((w // 2 - r, int(0.40 * h) - r, w // 2 + r, int(0.40 * h) + r), fill=accent)
    d.rectangle((0, int(0.78 * h), w, int(0.92 * h)), fill=(245, 242, 235))
    f = fit(title, int(0.8 * w), int(0.09 * h))
    l, t, rr, b = f.getbbox(title)
    d.text(((w - (rr - l)) / 2 - l, int(0.85 * h) - (b - t) / 2 - t), title, font=f, fill=(20, 20, 24))
    return im


def cutout(w, h, draw):
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    draw(ImageDraw.Draw(im), w, h)
    return im


def device(colour, stripe):
    def go(d, w, h):
        d.rounded_rectangle((0, 0, w - 1, h - 1), int(0.06 * min(w, h)), fill=colour)
        d.rectangle((int(0.08 * w), int(0.46 * h), int(0.92 * w), int(0.54 * h)), fill=stripe)
    return go


def person(skin, shirt, trousers):
    def go(d, w, h):
        hr = int(0.17 * w)                                       # head
        d.ellipse((w // 2 - hr, int(0.02 * h), w // 2 + hr, int(0.02 * h) + 2 * hr), fill=skin)
        top = int(0.02 * h) + 2 * hr + int(0.01 * h)
        d.rounded_rectangle((int(0.12 * w), top, int(0.88 * w), int(0.66 * h)), int(0.12 * w), fill=shirt)          # body and arms
        d.rectangle((int(0.24 * w), int(0.62 * h), int(0.48 * w), h - 1), fill=trousers)                         # legs, cut by the edge
        d.rectangle((int(0.52 * w), int(0.62 * h), int(0.76 * w), h - 1), fill=trousers)
    return go


def logo_disc(d, w, h):
    d.ellipse((0, 0, w - 1, h - 1), fill=(226, 92, 64))
    d.ellipse((int(0.2 * w), int(0.2 * h), int(0.8 * w), int(0.8 * h)), fill=(250, 240, 228))
    d.ellipse((int(0.36 * w), int(0.36 * h), int(0.64 * w), int(0.64 * h)), fill=(226, 92, 64))


def logo_white_margin(d, w, h):
    m = 211                                                      # transparent margin each side
    for i in range(3):                                           # three white bars, a wordmark's stand-in
        y0 = int(0.30 * h) + i * int(0.15 * h)
        d.rounded_rectangle((m, y0, w - 1 - m - i * int(0.12 * (w - 2 * m)), y0 + int(0.10 * h)), int(0.03 * h), fill=(255, 255, 255))


def logo_hexagon(d, w, h):
    cx, cy, r = w / 2, h / 2, min(w, h) / 2 - 1
    pts = [(cx + r * np.cos(np.pi / 6 + k * np.pi / 3), cy + r * np.sin(np.pi / 6 + k * np.pi / 3)) for k in range(6)]
    d.polygon(pts, fill=(64, 160, 200))
    rr = 0.45 * r
    d.ellipse((cx - rr, cy - rr, cx + rr, cy + rr), fill=(240, 248, 250))


