# covers padded with transparent margins (left, top, right, bottom) and an optional narrower cut of the cover itself
PADS = [
    ("pad_a.png", ((70, 110, 170), (20, 30, 60), (240, 180, 70)), (300, 50, 20, 200), 1.0),
    ("pad_b.png", ((170, 70, 90), (50, 20, 30), (120, 210, 230)), (0, 150, 420, 0), 0.7),
    ("pad_c.png", ((80, 150, 100), (20, 50, 30), (240, 120, 160)), (160, 0, 160, 320), 1.0),
]


def make_pads():
    out = []
    for i, (name, (top, bottom, accent), (l, t, r, b), wk) in enumerate(PADS):
        if (KIT / name).exists() and not FORCE:
            out.append(f"kit3/{name}")
            continue
        im = poster(1280, 1580, top, bottom, accent, 40 + i, title=name[4].upper()).convert("RGBA")
        im = im.resize((640, round(640 * im.height / im.width)), Image.LANCZOS)
        if wk < 1:
            cw = round(im.width * wk)
            x0 = (im.width - cw) // 2
            im = im.crop((x0, 0, x0 + cw, im.height))
        # a 4-px white frame on the cover's own edge: a still can't tell a dark cover edge from the stage
        frame = Image.new("RGBA", im.size, (255, 255, 255, 255))
        frame.paste(im.crop((4, 4, im.width - 4, im.height - 4)), (4, 4))
        im = frame
        canvas = Image.new("RGBA", (im.width + l + r, im.height + t + b), (0, 0, 0, 0))
        canvas.paste(im, (l, t))
        canvas.save(KIT / name)
        out.append(f"kit3/{name}")
    return out


# ------------------------------------------------------------------------------------------------------------------------ the run
def pictures():
    """every page and picture: public path -> a function that draws it"""
    I = f"{DEMO}/img"
    jobs = {f"{DEMO}/pages/{n}.png": (lambda n=n, v=v: draw_page(n, *v)) for n, v in PAGE_WORDS.items()}
    imgs = {
        f"{I}/cover.jpg": lambda: poster(1288, 1594, (40, 70, 120), (12, 16, 30), (230, 160, 60), 1),
        f"{I}/device_a.png": lambda: cutout(4007, 2384, device((70, 72, 78), (150, 156, 166))),
        f"{I}/device_b.png": lambda: cutout(3914, 2658, device((200, 202, 206), (90, 94, 102))),
        f"{I}/device_c.png": lambda: cutout(1930, 3427, device((236, 236, 232), (40, 42, 48))),
        f"{I}/person_a.png": lambda: cutout(892, 1513, person((214, 170, 140), (60, 90, 150), (40, 40, 48))),
        f"{I}/person_b.png": lambda: cutout(1034, 1705, person((150, 104, 80), (190, 70, 60), (60, 56, 50))),
        f"{I}/person_c.png": lambda: cutout(819, 1526, person((230, 196, 170), (70, 140, 90), (36, 44, 70))),
        f"{I}/logo_a.png": lambda: cutout(700, 620, logo_disc),
        f"{I}/logo_b.png": lambda: cutout(2000, 2000, logo_white_margin),
        f"{I}/logo_c.png": lambda: cutout(960, 968, logo_hexagon),
        f"{I}/still.png": still,
    }
    for rel, make in imgs.items():
        jobs[rel] = (lambda rel=rel, make=make: make().save(PUB / rel, quality=93) if rel.endswith(".jpg") else make().save(PUB / rel, optimize=True))
    return jobs


def link(rel):
    src, dst = PUB / rel, LEAN / rel
    if not src.exists():
        raise SystemExit(f"missing {src}")
    dst.parent.mkdir(parents=True, exist_ok=True)
    if dst.exists():
        return
    os.link(src, dst)


def main():
    for sub in ("pages", "img", "clips"):
        (KIT / "demo" / sub).mkdir(parents=True, exist_ok=True)
    made = []
    for rel, draw in pictures().items():
        if FORCE or not (PUB / rel).exists():
            draw()
        made.append(rel)
    durs = json.loads(CLIPDURS.read_text(encoding="utf-8")) if CLIPDURS.exists() else {}
    for rel, (fps, secs, seed, c0, c1, speed, boxes) in CLIPS.items():
        if FORCE or not (PUB / rel).exists() or rel not in durs:
            durs[rel] = list(field_clip(PUB / rel, fps, secs, seed, c0, c1, speed, boxes))
        made.append(rel)
    CLIPDURS.write_text(json.dumps(dict(sorted(durs.items())), indent=1) + "\n", encoding="utf-8")
    made += make_pads()
    for rel in made:
        link(rel)
    size = sum(f.stat().st_size for f in LEAN.rglob("*") if f.is_file())
    print(f"{LEAN}: {len(made)} files, {size / 1e6:.0f} MB (hard links); {len(CLIPS)} clips in {CLIPDURS.name}")


if __name__ == "__main__":
    main()
