"""kit3_demo_assets.py: the media kit3's demo (src/kit3/Kit3Demo.tsx) and its proof (kit3_proof.mjs, kit3_check.py) need, DRAWN HERE.

No footage, photo or logo of anyone's: every page, picture and clip is generated by this script (words on paper, solid shapes, moving
colour fields), so the proof runs on any PC and nothing in it needs a licence. The creator's own material never goes into the demo:
the demo proves the kit, the videos use the real thing.

  EDIT tools/motion/kit3_demo_assets.py [--force]

1. Draws the demo's files into PUBLIC/kit3/ (kept: the proof re-runs on them; --force draws them again). Public-dir paths:
   kit3/demo/pages/  page_light.png (3210x1069), page_dark.png (1152x989), page_headline.png (1050x470), page_header.png (909x329),
                     page_number.png (1802x485): page captures with their words inside the loose boxes Kit3Demo.tsx marks (PAGE_WORDS
                     below: the kit snaps a loose box to its ink); page_header's crop holds only its marked words (the refusal case "needs
                     no mark"); page_light keeps [1000, 420, 120, 50] blank (the refusal case "no ink under its box").
   kit3/demo/img/    cover.jpg (a poster), device_a/b/c.png (three cut-outs of different widths: a row's names wider than their figures),
                     person_a/b/c.png (three people cut at the legs, for the bleed row), logo_a/b/c.png (logo_b white with 211 px of
                     transparent margin each side: logos are centred by their visible pixels), still.png (1920x885, four things at the
                     still's four mark boxes).
   kit3/demo/clips/  ground_a.mp4, ground_b.mp4, ground_c.mp4 (moving colour fields behind pages and rows), subject.mp4 (2.3 s at 30 fps,
                     a shape where its mark sits on a field that moves everywhere: the clip plays, the mark freezes it).
   kit3/pad_a.png, pad_b.png, pad_c.png: three covers with transparent margins of different sizes on every side, so a row placed by the
                     files' boxes instead of their visible pixels shows off centre with unequal gaps; one is cut narrower so the visible
                     widths differ too.
2. Registers the clips in src/clipdurs.json ([the last frame's start in s, fps]: Foot refuses a clip with no measured length).
3. Builds TMP/pub_kit3: hard links of exactly the files the demo uses, at the same paths as in PUBLIC, so a stills run bundles a few
   MB instead of the whole public dir. Existing links are kept.
"""
