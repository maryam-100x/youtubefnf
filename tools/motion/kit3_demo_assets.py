def field_clip(out, fps, seconds, seed, c0, c1, speed, boxes, w=1920, h=1080):
    """a moving colour field (three travelling waves, drawn at 1/8 size and scaled up: smooth, cheap), solid boxes on top"""
    n = round(seconds * fps)
    sw, sh = w // 8, h // 8
    yy, xx = np.mgrid[0:sh, 0:sw].astype(np.float32)
    rng = np.random.default_rng(seed)
    waves = [(rng.uniform(0.02, 0.05), rng.uniform(0, 2 * np.pi), rng.uniform(-1, 1), rng.uniform(-1, 1)) for _ in range(3)]
    c0, c1 = np.array(c0, np.float32), np.array(c1, np.float32)
    vf = f"scale={w}:{h}:flags=bicubic" + "".join(f",drawbox=x={x}:y={y}:w={bw}:h={bh}:color={col}:t=fill" for x, y, bw, bh, col in boxes)
    cmd = [FFMPEG, "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{sw}x{sh}", "-r", str(fps), "-i", "-",
           "-vf", vf, "-an", "-c:v", "libx264", "-crf", "18", "-preset", "medium", "-pix_fmt", "yuv420p", "-movflags", "+faststart",
           str(out)]
    p = subprocess.Popen(cmd, stdin=subprocess.PIPE)
    for i in range(n):
        ph = 2 * np.pi * speed * i / fps
        v = sum(np.sin(2 * np.pi * k * (xx * dx + yy * dy) + p0 + ph) for k, p0, dx, dy in waves) / 3      # -1..1
        u = ((v + 1) / 2)[..., None]
        p.stdin.write(np.clip(c0 * (1 - u) + c1 * u, 0, 255).astype(np.uint8).tobytes())
    p.stdin.close()
    if p.wait():
        raise SystemExit(f"kit3_demo_assets: ffmpeg failed on {out}")
    return round((n - 1) / fps, 4), float(fps)


