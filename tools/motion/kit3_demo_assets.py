INK_SHARE = 0.62    # a line's ink height as a share of its box (the loose box of a page's DOM: blank above and below the words)


def font(size):
    for f in ("arialbd.ttf", "arial.ttf", "DejaVuSans-Bold.ttf", "DejaVuSans.ttf",
              "/System/Library/Fonts/Supplemental/Arial Bold.ttf", "/System/Library/Fonts/Supplemental/Arial.ttf",
              "/Library/Fonts/Arial.ttf", "/System/Library/Fonts/Helvetica.ttc"):
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            continue
    try:
        return ImageFont.load_default(size)
    except TypeError:
        raise SystemExit("kit3_demo_assets: no TrueType font found (and Pillow is older than 10.1): install one, e.g. DejaVu Sans")


def fit(text, w, h):
    """the biggest font whose ink of `text` fits w x h"""
    lo, hi = 6, 400
    while lo < hi:
        mid = (lo + hi + 1) // 2
        l, t, r, b = font(mid).getbbox(text)
        if r - l <= w and b - t <= h:
            lo = mid
        else:
            hi = mid - 1
    return font(lo)


def draw_page(name, size, paper, ink, parts):
    im = Image.new("RGB", size, paper)
    d = ImageDraw.Draw(im)
    marked = [p for p in parts if p[2]]
    # one size for the page's marked lines (a page has one body size): the largest that fits every marked box
    body = min((fit(t, b[2] - 8, round(b[3] * INK_SHARE)).size for t, b, _m in marked), default=40)
    for text, (x, y, w, h), is_marked in parts:
        f = font(body) if is_marked else fit(text, w - 8, round(h * INK_SHARE))
        l, t, r, b = f.getbbox(text)
        grey = ink if is_marked else tuple(int(0.55 * a + 0.45 * p) for a, p in zip(ink, paper))
        d.text((x + 3 - l, y + (h - (b - t)) / 2 - t), text, font=f, fill=grey)
    if name == "page_light":            # the page's right column: thumbnails beside the "up next" titles (outside the demo's crop)
        for i in range(3):
            d.rounded_rectangle((1300, 290 + 120 * i, 1660, 390 + 120 * i), 10, fill=(214, 214, 214))
    im.save(KIT / "demo" / "pages" / f"{name}.png", optimize=True)


