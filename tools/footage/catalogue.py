"""The permanent footage catalogue: where every kind of moment sits in the creator's sources (the videos, stills and clips of
kb/footage/sources.json), sorted by theme with exact times, a 9:16 crop note and a star on the best picks, so a pick is the best moment
that exists, not the first one that roughly fits. The data is kb/footage/catalogue.json (theme -> entries; it starts as {}); the
markdown (kb/FOOTAGE.md's generated block and kb/footage/<theme>.md) and the contact sheets (FOOTAGE/index/catalogue/<theme>.jpg) are
generated from it. Edit the json, then run md (and sheets for the themes you touched).

  PIPE tools/footage/catalogue.py md                      # write FOOTAGE.md's block + footage/<theme>.md
  PIPE tools/footage/catalogue.py sheets [theme ...]      # contact sheets (all themes when none given)
  PIPE tools/footage/catalogue.py find <word> [<word> ...] [--sheet out.jpg]
  PIPE tools/footage/catalogue.py coverage                # is every shot and still the brain holds in a theme?
  PIPE tools/footage/catalogue.py check                   # same moment with different notes, bad paths

catalogue.json: {"updated": "<date>", "themes": {"<theme id>": {"title", "intro", "file": "footage/<theme id>.md", "groups": [names],
"entries": [entry]}}, "best_of": [{"subject", "theme", "picks": [pick keys]}]}
Entry fields: src (a video key of sources.json, a stills key, or CLIP = a clip file), in/out (m:ss.xx) + start_s/end_s for video,
path (relative to FOOTAGE) for stills and clips, group, note, star, crop (L / C / R / wide = where the subject sits in a 9:16 crop),
flags (dark, ovl, txt, lbx, ui, short, quiet, action)."""
import argparse
import hashlib
import json
import re
import subprocess
import sys
import textwrap
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image, ImageDraw

sys.path.insert(0, str(Path(__file__).resolve().parent))
import brain_lib as B  # noqa: E402
from sheetfont import font as sheet_font  # noqa: E402

KB = B.KB
CAT = B.CATALOGUE
GUIDE = KB / "FOOTAGE.md"
ROOT = B.FOOTAGE
SHEETS = ROOT / "index" / "catalogue"
FRAMES = SHEETS / "_frames"
CROP = {"L": "left", "C": "centre", "R": "right", "wide": "wide (no single subject)"}
FLAG = {"dark": "dark", "ovl": "overlay baked in", "txt": "text on screen", "lbx": "letterboxed", "ui": "on-screen interface", "short": "very short",
        "quiet": "quiet", "action": "action"}
START, END = "<!-- catalogue:start (generated by tools/footage/catalogue.py md; edit catalogue.json, not this block) -->", "<!-- catalogue:end -->"


def load():
    cat = B.catalogue()
    cat.setdefault("themes", {})
    cat.setdefault("best_of", [])
    cat.setdefault("updated", "")
    return cat


def is_video(src):
    return src in B.MASTERS


def slug(s):
    return re.sub(r"[^a-z0-9 \-]", "", s.lower()).replace(" ", "-")


def ref(x):
    """Short reference of an entry: 'A1 11:52.95-11:54.93' or 'IMG people/...'."""
    if is_video(x["src"]):
        return f"{x['src']} {x['in']}-{x['out']}"
    if x["src"] == "CLIP":
        return f"CLIP {x['path']} {x['in']}-{x['out']}"
    return f"{x['src']} {x['path']}"


def line(x):
    star = "★ " if x["star"] else ""
    if is_video(x["src"]):
        head = f"**{x['src']} {x['in']}-{x['out']}** ({x['start_s']:.2f}-{x['end_s']:.2f} s, {x['end_s'] - x['start_s']:.2f} s)"
    elif x["src"] == "CLIP":
        head = f"**CLIP** `{x['path']}` ({x['in']}-{x['out']})"
    else:
        head = f"**{x['src']}** `{x['path']}`"
    tail = [f"9:16 {CROP.get(x['crop'], x['crop'])}"] + [FLAG.get(f, f) for f in x["flags"]]
    return f"- {star}{head} {x['note']} _({' · '.join(tail)})_"


def sources_line():
    vids = [f"{k} = {m['title']}" for k, m in B.MASTERS.items()]
    stills = [f"{k} = stills ({B.rel_footage(p)})" for k, p in B.STILLS.items()]
    return "; ".join(vids + stills + ["CLIP = a clip file"])


def md():
    cat = load()
    th = cat["themes"]
    for tid, T in th.items():
        out = [f"# {T['title']}", "", T["intro"], "",
               f"Contact sheet: `FOOTAGE/index/catalogue/{tid}.jpg` (more pages: `{tid}_2.jpg`, ...). Regenerate: "
               f"`PIPE tools/footage/catalogue.py sheets {tid}`. Generated from `kb/footage/catalogue.json` "
               f"({cat['updated']}); edit the json, then run `catalogue.py md`.", "",
               "How to read an entry: source + time range (`m:ss.xx` in that video, seconds in brackets), what happens, then the crop note "
               "(where the subject sits in a 9:16 frame) and flags. ★ = best pick. Sources: " + sources_line() + "; paths are under "
               "`FOOTAGE/`.", ""]
        stars = [x for x in T["entries"] if x["star"]]
        out.append("Groups: " + " · ".join(f"[{g}](#{slug(g)}) ({sum(1 for x in T['entries'] if x['group'] == g)})" for g in T["groups"]))
        out.append("")
        if stars:
            out += [f"**Best picks ({len(stars)}):** " + "; ".join(f"{ref(x)} ({x['group']})" for x in stars[:12]) +
                    ("; ..." if len(stars) > 12 else ""), ""]
        for g in T["groups"]:
            es = [x for x in T["entries"] if x["group"] == g]
            out += [f"## {g}", ""] + [line(x) for x in es] + [""]
        (KB / T["file"]).parent.mkdir(parents=True, exist_ok=True)
        (KB / T["file"]).write_text("\n".join(out), encoding="utf-8")
    # FOOTAGE.md generated block: themes table + best-of table
    idx = {}
    for tid, T in th.items():
        for x in T["entries"]:
            idx.setdefault(pick_key(x), x)
    blk = [START, "", "## Themes", "", "| Theme | Entries | ★ | Sheet |", "|---|---|---|---|"]
    for tid, T in th.items():
        blk.append(f"| [{T['title']}]({T['file']}) | {len(T['entries'])} | {sum(x['star'] for x in T['entries'])} | `catalogue/{tid}.jpg` |")
    blk += ["", "## Best of: the hero moments for the most common subjects", "", "| Subject | Hero moments | Theme |", "|---|---|---|"]
    for b in cat["best_of"]:
        picks = []
        for p in b["picks"]:
            x = idx.get(p)
            picks.append(f"**{p}** {x['note'][:90]}{'...' if len(x['note']) > 90 else ''}" if x else f"**{p}** (not found)")
        blk.append(f"| {b['subject']} | {'<br>'.join(picks)} | [{th[b['theme']]['title']}]({th[b['theme']]['file']}) |")
    blk += ["", END]
    text = GUIDE.read_text(encoding="utf-8") if GUIDE.exists() else ""
    if START.split(" (")[0] in text and END in text:
        a = text.index(START.split(" (")[0])
        b = text.index(END) + len(END)
        text = text[:a] + "\n".join(blk) + text[b:]
    else:
        text = text.rstrip() + "\n\n" + "\n".join(blk) + "\n"
    GUIDE.write_text(text, encoding="utf-8")
    print(len(th), "theme files +", GUIDE)


def pick_key(x):
    """The key best_of uses: 'A1 11:52.95-11:54.93', '<stills key> <file name>', 'CLIP <clip stem>'."""
    if is_video(x["src"]):
        return f"{x['src']} {x['in']}-{x['out']}"
    if x["src"] == "CLIP":
        return f"CLIP {Path(x['path']).stem}"
    return f"{x['src']} {Path(x['path']).name}"


def font(size):
    return sheet_font(size, bold=False)


def frame(src, t, w=192, h=108):
    """A cached small frame of a video at t seconds (from the 480p proxy when there is one)."""
    FRAMES.mkdir(parents=True, exist_ok=True)
    stem = src if is_video(src) else Path(src).stem
    p = FRAMES / f"{B.key_file(stem)}_{int(round(t * 1000)):08d}.jpg"
    if not p.exists():
        vid = B.proxy_or_file(src) if is_video(src) else ROOT / src
        subprocess.run([B.FFMPEG, "-v", "error", "-y", "-ss", f"{t:.3f}", "-i", str(vid), "-frames:v", "1", "-vf",
                        f"scale={w}:{h}:force_original_aspect_ratio=decrease,pad={w}:{h}:(ow-iw)/2:(oh-ih)/2", "-q:v", "3", str(p)],
                       capture_output=True)
    return p


def still(path, w=192, h=108):
    """A cached thumbnail of a still (fits w x h)."""
    FRAMES.mkdir(parents=True, exist_ok=True)
    p = FRAMES / f"img_{hashlib.md5(path.encode()).hexdigest()[:12]}.jpg"
    if not p.exists():
        try:
            im = Image.open(ROOT / path)
            im.draft("RGB", (w * 2, h * 2))
            im = im.convert("RGB")
            im.thumbnail((w, h))
            im.save(p, quality=88)
        except Exception:  # noqa: BLE001
            Image.new("RGB", (w, h), "grey").save(p)
    return p


def thumbs(x):
    """1-3 thumbnail files for an entry: video = frames at 20/50/80 % of the range, still = the picture."""
    if is_video(x["src"]) or x["src"] == "CLIP":
        a, b = x["start_s"], x["end_s"]
        ts = [a + (b - a) * f for f in (0.2, 0.5, 0.8)] if b - a > 0.6 else [(a + b) / 2]
        src = x["src"] if is_video(x["src"]) else x["path"]
        return [frame(src, t) for t in ts]
    return [still(x["path"])]


def sheet(entries, out, title=""):
    """3 entries per row; each cell = up to 3 frames + label (star, source, time, group) + note."""
    W, H, CW, COLS, PER = 192, 108, 600, 3, 45
    f1, f2 = font(13), font(12)
    with ThreadPoolExecutor(4) as ex:
        tl = list(ex.map(thumbs, entries))
    pages = [list(range(i, min(i + PER, len(entries)))) for i in range(0, len(entries), PER)] or [[]]
    files = []
    for pi, idxs in enumerate(pages):
        rows = (len(idxs) + COLS - 1) // COLS
        CH = H + 60
        top = 26 if title else 0
        im = Image.new("RGB", (COLS * CW, top + max(1, rows) * CH), "white")
        d = ImageDraw.Draw(im)
        if title:
            d.text((6, 4), f"{title}  ({len(entries)} entries, page {pi + 1}/{len(pages)})", fill="black", font=font(16))
        for k, i in enumerate(idxs):
            x = entries[i]
            cx, cy = (k % COLS) * CW + 6, top + (k // COLS) * CH
            ths = tl[i]
            for j, p in enumerate(ths):
                try:
                    t = Image.open(p).convert("RGB")
                except Exception:  # noqa: BLE001
                    t = Image.new("RGB", (W, H), "grey")
                t.thumbnail((W, H))
                im.paste(t, (cx + j * W + (W - t.width) // 2, cy + (H - t.height) // 2))
            star = "* " if x["star"] else ""
            lab = f"{star}{x['src']} {x['in']}-{x['out']}" if "in" in x else f"{star}{x['src']} {Path(x['path']).name}"
            d.text((cx, cy + H + 2), f"{lab}   [{x['group']}]"[:92], fill="#b00000" if x["star"] else "black", font=f1)
            if len(ths) == 1 and not is_video(x["src"]) and x["src"] != "CLIP":
                for k2, ln in enumerate(textwrap.wrap(x["note"], 60)[:7]):
                    d.text((cx + W + 8, cy + 2 + k2 * 15), ln, fill="#222", font=f2)
            else:
                for k2, ln in enumerate(textwrap.wrap(x["note"], 92)[:3]):
                    d.text((cx, cy + H + 18 + k2 * 14), ln, fill="#222", font=f2)
        name = out if pi == 0 else out.with_name(f"{out.stem}_{pi + 1}{out.suffix}")
        im.save(name, quality=82)
        files.append(name)
    return files


def sheets(which):
    cat = load()
    SHEETS.mkdir(parents=True, exist_ok=True)
    for tid, T in cat["themes"].items():
        if which and tid not in which:
            continue
        files = sheet(T["entries"], SHEETS / f"{tid}.jpg", T["title"])
        print(tid, len(T["entries"]), "->", ", ".join(str(f) for f in files))


def find(words, out=None):
    cat = load()
    seen = {}
    for tid, T in cat["themes"].items():
        for x in T["entries"]:
            hay = f"{x['note']} {x['group']} {T['title']} {x.get('path', '')}".lower()
            n = sum(1 for w in words if re.search(r"\b" + re.escape(w.lower()), hay))
            if n:
                k = ref(x)
                if k not in seen:
                    seen[k] = [n, x, set()]
                seen[k][0] = max(seen[k][0], n)
                seen[k][2].add(f"{tid}/{x['group']}" + ("*" if x["star"] else ""))
    res = sorted(seen.values(), key=lambda s: (-s[0], not any(t.endswith("*") for t in s[2]), ref(s[1])))
    for n, x, tags in res:
        print(f"[{n}] {ref(x)}  {x['note']}  <{', '.join(sorted(tags))}>")
    print(len(res), "moments")
    if out:
        ents = [dict(x, group=sorted(t)[0]) for _, x, t in res[:60]]
        print(sheet(ents, Path(out), "find: " + " ".join(words)))


def brain_records():
    """Every record the footage brain holds (kb/footage/brain/*.json): the index the catalogue is checked against."""
    recs = []
    for p in sorted(B.BRAIN.glob("*.json")):
        try:
            recs += json.loads(p.read_text(encoding="utf-8")).get("shots", [])
        except (OSError, ValueError):
            continue
    return recs


def coverage():
    """Every shot of a master the brain holds, every still: in at least one theme? A shot counts when themes cover half of it (or any
    of a shot under 0.8 s)."""
    cat = load()
    iv = {k: [] for k in B.MASTERS}
    paths = set()
    for T in cat["themes"].values():
        for x in T["entries"]:
            if x["src"] in iv:
                iv[x["src"]].append((x["start_s"], x["end_s"]))
            if "path" in x:
                paths.add(x["path"].replace("\\", "/"))
    cnt, miss = {}, []
    for r in brain_records():
        if r.get("kind") == "image":
            t = "still"
            rel = B.rel_footage(r["file"])
            ok = rel in paths or any(B.rel_footage(v) in paths for v in r.get("variants", []))
            if not ok:
                miss.append(f"{r['id']}  {r.get('desc', '')[:80]}")
        elif r["src"] in iv:
            t = "video_shot"
            a, b = r["in"], r["out"]
            segs = sorted((max(a, p), min(b, q)) for p, q in iv[r["src"]] if q > a and p < b)
            cov, cur = 0.0, a
            for p, q in segs:
                if q > cur:
                    cov += q - max(p, cur)
                    cur = q
            ok = cov >= 0.5 * (b - a) or (b - a < 0.8 and cov > 0)
            if not ok:
                miss.append(f"{r['src']} {B.mmss(a)}-{B.mmss(b)}  covered {cov:.2f}/{b - a:.2f} s  {r.get('desc', '')[:80]}")
        else:
            continue
        cnt.setdefault(t, [0, 0])
        cnt[t][1] += 1
        cnt[t][0] += ok
    for t, (c, n) in cnt.items():
        print(f"{t:11s} {c}/{n} in at least one theme")
    for m in miss:
        print("  MISSING", m)
    extra = [p for p in paths if not (ROOT / p).exists()]
    for p in extra:
        print("  BAD PATH", p)
    return cnt, miss


def check():
    cat = load()
    notes = {}
    for tid, T in cat["themes"].items():
        for x in T["entries"]:
            notes.setdefault(ref(x), set()).add(x["note"])
            if "path" in x and not (ROOT / x["path"]).exists():
                print("BAD PATH", tid, x["path"])
    for k, v in notes.items():
        if len(v) > 1:
            print("DIFFERENT NOTES", k, v)
    print(len(notes), "distinct moments checked")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["md", "sheets", "find", "coverage", "check"])
    ap.add_argument("args", nargs="*")
    ap.add_argument("--sheet")
    a = ap.parse_args()
    if a.cmd == "md":
        md()
    elif a.cmd == "sheets":
        sheets(set(a.args))
    elif a.cmd == "find":
        if not a.args:
            sys.exit("find needs words")
        find(a.args, a.sheet)
    elif a.cmd == "coverage":
        coverage()
    else:
        check()


if __name__ == "__main__":
    main()
